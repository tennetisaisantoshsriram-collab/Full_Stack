// ============================================================
// Q6: Node.js Built-in Modules — os, path, fs
// ============================================================

const os   = require("os");    // Operating System info
const path = require("path");  // File path utilities
const fs   = require("fs");    // File System operations

// -----------------------------------------------------------
// PART A: os Module — Operating System Information
// -----------------------------------------------------------

console.log("====== os MODULE ======");

console.log("Platform        :", os.platform());     // e.g., win32, linux, darwin
console.log("OS Type         :", os.type());          // e.g., Windows_NT, Linux
console.log("Architecture    :", os.arch());          // e.g., x64
console.log("Hostname        :", os.hostname());      // computer name
console.log("Home Directory  :", os.homedir());       // user's home folder
console.log("Temp Directory  :", os.tmpdir());        // system temp folder
console.log("Total Memory    :", (os.totalmem() / (1024 ** 3)).toFixed(2), "GB");
console.log("Free Memory     :", (os.freemem()  / (1024 ** 3)).toFixed(2), "GB");
console.log("CPU Cores       :", os.cpus().length);
console.log("First CPU Model :", os.cpus()[0].model);
console.log("Uptime          :", Math.floor(os.uptime() / 3600), "hours");

// Network interfaces
const interfaces = os.networkInterfaces();
const eth = Object.keys(interfaces)[0];
console.log("\nFirst Network Interface:", eth);


// -----------------------------------------------------------
// PART B: path Module — File Path Utilities
// -----------------------------------------------------------

console.log("\n====== path MODULE ======");

const filePath = "/users/student/projects/app/index.js";

console.log("Full path       :", filePath);
console.log("Directory name  :", path.dirname(filePath));    // /users/student/projects/app
console.log("Base name       :", path.basename(filePath));   // index.js
console.log("Extension       :", path.extname(filePath));    // .js
console.log("File name only  :", path.basename(filePath, path.extname(filePath))); // index

// Joining paths safely (handles OS-specific separators)
const joined = path.join("users", "student", "docs", "notes.txt");
console.log("path.join()     :", joined);

// Resolving an absolute path
const resolved = path.resolve("Q6-Node-Modules", "modules.js");
console.log("path.resolve()  :", resolved);

// Normalize a messy path
const messy = "users//student/../student/./docs/notes.txt";
console.log("path.normalize():", path.normalize(messy));

// Check if a path is absolute
console.log("Is absolute?    :", path.isAbsolute(filePath));  // true
console.log("Is absolute?    :", path.isAbsolute("relative/path")); // false

// Parse a path into components
const parsed = path.parse(filePath);
console.log("path.parse()    :", parsed);


// -----------------------------------------------------------
// PART C: fs Module — File System Operations
// -----------------------------------------------------------

console.log("\n====== fs MODULE ======");

const fileName  = path.join(__dirname, "sample.txt");
const copyName  = path.join(__dirname, "sample_copy.txt");

// 1. Write a file (creates or overwrites)
fs.writeFileSync(fileName, "Hello from Node.js!\nThis is line 2.\nThis is line 3.\n");
console.log("File written    :", fileName);

// 2. Append to a file
fs.appendFileSync(fileName, "This line was appended.\n");
console.log("Data appended to:", fileName);

// 3. Read a file synchronously
const content = fs.readFileSync(fileName, "utf8");
console.log("\n--- File Contents ---");
console.log(content);

// 4. Check if file exists
const exists = fs.existsSync(fileName);
console.log("File exists?    :", exists);

// 5. Get file stats (metadata)
const stats = fs.statSync(fileName);
console.log("File size       :", stats.size, "bytes");
console.log("Is a file?      :", stats.isFile());
console.log("Is a directory? :", stats.isDirectory());
console.log("Last modified   :", stats.mtime.toLocaleString());

// 6. Copy a file
fs.copyFileSync(fileName, copyName);
console.log("File copied to  :", copyName);

// 7. List files in current directory
const files = fs.readdirSync(__dirname);
console.log("\nFiles in directory:", files);

// 8. Create a directory
const newDir = path.join(__dirname, "output");
if (!fs.existsSync(newDir)) {
    fs.mkdirSync(newDir);
    console.log("Directory created:", newDir);
} else {
    console.log("Directory already exists:", newDir);
}

// 9. Async file read with callback
console.log("\n--- Asynchronous Read ---");
fs.readFile(fileName, "utf8", (err, data) => {
    if (err) {
        console.error("Error reading file:", err.message);
        return;
    }
    console.log("Async read successful. First line:", data.split("\n")[0]);
});

// 10. Rename / move a file
const renamedFile = path.join(__dirname, "renamed.txt");
fs.copyFileSync(fileName, renamedFile);
fs.renameSync(renamedFile, path.join(__dirname, "output", "moved_file.txt"));
console.log("File moved to output/moved_file.txt");

// 11. Delete a file
fs.unlinkSync(copyName);
console.log("Deleted file    :", copyName);

console.log("\nAll fs operations completed successfully.");
